struct TempIntegrationDir {
    path: PathBuf,
}

impl TempIntegrationDir {
    fn new(prefix: &str) -> Self {
        for attempt in 0..100 {
            let timestamp = SystemTime::now()
                .duration_since(UNIX_EPOCH)
                .unwrap_or_default()
                .as_nanos();
            let path = std::env::temp_dir().join(format!(
                "devos-int-{prefix}-{}-{timestamp}-{attempt}",
                std::process::id()
            ));
            match fs::create_dir(&path) {
                Ok(()) => return Self { path },
                Err(err) if err.kind() == std::io::ErrorKind::AlreadyExists => continue,
                Err(err) => panic!("Falha ao criar diretório temporário de integração: {err}"),
            }
        }
        panic!("Não foi possível alocar diretório temporário exclusivo para o teste de integração");
    }

    fn path(&self) -> &Path {
        &self.path
    }
}

impl Drop for TempIntegrationDir {
    fn drop(&mut self) {
        let _ = fs::remove_dir_all(&self.path);
    }
}

