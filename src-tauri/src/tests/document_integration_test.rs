struct TempIntegrationDir {
    path: PathBuf,
}

impl TempIntegrationDir {
    fn new(prefix: &str) -> Self {
        for attempt in 0..100 {
            let timestamp = SystemTime::now()
                .duration_since(UNIX_EPOCH)
                .unwrap_or_default()
                .as_nanos();
            let path = std::env::temp_dir().join(format!(
                "devos-int-{prefix}-{}-{timestamp}-{attempt}",
                std::process::id()
            ));
            match fs::create_dir(&path) {
                Ok(()) => return Self { path },
                Err(err) if err.kind() == std::io::ErrorKind::AlreadyExists => continue,
                Err(err) => panic!("Falha ao criar diretório temporário de integração: {err}"),
            }
        }
        panic!("Não foi possível alocar diretório temporário exclusivo para o teste de integração");
    }

    fn path(&self) -> &Path {
        &self.path
    }
}

impl Drop for TempIntegrationDir {
    fn drop(&mut self) {
        let _ = fs::remove_dir_all(&self.path);
    }
}

#[test]
fn test_desktop_vault_capability_includes_generate_document_permission() {
    let cap_path = Path::new("capabilities/desktop-vault.json");
    assert!(
        cap_path.exists(),
        "capabilities/desktop-vault.json deve existir"
    );

    let content =
        fs::read_to_string(cap_path).expect("capabilities/desktop-vault.json deve ser legível");
    let val: serde_json::Value =
        serde_json::from_str(&content).expect("JSON de capability inválido");

    let permissions = val
        .get("permissions")
        .and_then(|p| p.as_array())
        .expect("Campo permissions deve ser um array");

    let has_doc_perm = permissions
        .iter()
        .any(|p| p.as_str() == Some("allow-generate-document"));

    assert!(
        has_doc_perm,
        "Manifesto desktop-vault.json deve conter a permissão 'allow-generate-document'"
    );
}

