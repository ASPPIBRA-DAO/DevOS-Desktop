#[test]
fn test_desktop_vault_capability_includes_generate_document_permission() {
    let cap_path = Path::new("capabilities/desktop-vault.json");
    assert!(
        cap_path.exists(),
        "capabilities/desktop-vault.json deve existir"
    );

    let content =
        fs::read_to_string(cap_path).expect("capabilities/desktop-vault.json deve ser legível");
    let val: serde_json::Value =
        serde_json::from_str(&content).expect("JSON de capability inválido");

    let permissions = val
        .get("permissions")
        .and_then(|p| p.as_array())
        .expect("Campo permissions deve ser um array");

    let has_doc_perm = permissions
        .iter()
        .any(|p| p.as_str() == Some("allow-generate-document"));

    assert!(
        has_doc_perm,
        "Manifesto desktop-vault.json deve conter a permissão 'allow-generate-document'"
    );
}

#[test]
fn test_autogenerated_acl_contains_generate_document() {
    let acl_path = Path::new("permissions/autogenerated/generate_document.toml");
    assert!(
        acl_path.exists(),
        "permissions/autogenerated/generate_document.toml deve existir"
    );

    let content = fs::read_to_string(acl_path).expect("generate_document.toml deve ser legível");
    assert!(content.contains("allow-generate-document"));
    assert!(content.contains("deny-generate-document"));
    assert!(content.contains("generate_document"));
}

#[test]
fn test_generate_document_integration_citizen_ledger_end_to_end() {
    let unique_name = format!(
        "int_citizen_ledger_{}.pdf",
        chrono::Utc::now().timestamp_micros()
    );

    let payload = GenerateDocumentPayload {
        request: DocumentRequest::CitizenLedger(CitizenLedgerPayload {
            associate_id: Some("ASSOC-INT-2026".to_string()),
            data: json!({
                "meta": {
                    "generated_at": "23/10/2026",
                    "reference_period": "2026-10",
                    "audit_hash": "audit_keccak_hash_test_e2e"
                },
                "associate": {
                    "id": "ASSOC-INT-2026",
                    "name": "Andressa de Lima Ferreira",
                    "cpf": "173.793.567-80",
                    "email": "andressa.ferreira@asppibra.org.br",
                    "avatar_letter": "A",
                    "address_line1": "Rua Palmira F. De Carvalho, lote 05, Quadra D",
                    "address_line2": "São José de Imbassaí, Maricá - RJ, 24912-000"
                },
                "summary": {
                    "total_contracted": "65.000,00",
                    "total_paid": "36.623,00",
                    "outstanding_balance": "27.377,00"
                },
                "transactions": [
                    {
                        "date": "08/08/2023",
                        "counterparty": "Paulo Roberto Batista Ferreira",
                        "origin": "Itaú Unibanco S.A.",
                        "destination": "Nu Pagamentos S.A.",
                        "amount": "5.000,00",
                        "direction": "inbound",
                        "status_label": "Concluído",
                        "status_variant": "confirmed"
                    }
                ]
            }),
        }),
        open_after_export: Some(false),
        target_file_name: Some(unique_name.clone()),
    };

    let result = generate_document(payload).expect(
        "Comando IPC unificado generate_document deve executar com sucesso para CitizenLedger",
    );

    assert!(result.success, "Resultado deve indicar sucesso");
    assert_eq!(result.metadata.document_kind, DocumentKind::CitizenLedger);
    assert_eq!(result.file_name, unique_name);
    assert!(!result.metadata.sha256_checksum.is_empty());

    let path = Path::new(&result.file_path);
    assert!(path.exists(), "Arquivo gerado deve existir no disco");

    let read_bytes = fs::read(path).expect("Arquivo gerado deve ser legível no disco");
    assert!(
        read_bytes.len() > 1000,
        "PDF gerado deve ter tamanho substancial"
    );
    assert_eq!(
        &read_bytes[0..5],
        b"%PDF-",
        "Cabeçalho do PDF deve ser canônico %PDF-"
    );

    // Verificar se o checksum gerado pelo backend coincide com o hash do binário físico
    let disk_checksum = hex::encode(keccak256(&read_bytes));
    assert_eq!(
        disk_checksum, result.metadata.sha256_checksum,
        "Checksum nos metadados deve coincidir com o hash do arquivo em disco"
    );

    // Limpeza
    let _ = fs::remove_file(path);
}

