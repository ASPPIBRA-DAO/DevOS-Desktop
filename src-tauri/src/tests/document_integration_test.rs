#[test]
fn test_generate_document_integration_cessao_posse_scope_and_temp_dir_end_to_end() {
    let temp_dir = TempIntegrationDir::new("cessao-posse");
    let unique_name = format!("int_cessao_{}.pdf", chrono::Utc::now().timestamp_micros());

    let payload = GenerateDocumentPayload {
        request: DocumentRequest::CessaoPosse(CessaoPossePayload {
            document_number: "2026-INT-0001/CP".to_string(),
            auth_code: "AUTH-INT-2026".to_string(),
            data: json!({
                "cedenteNome": "JOÃO CARLOS DA SILVA",
                "cessionarioNome": "MARIA FERNANDA SOUZA",
                "imovelLote": "15",
                "imovelQuadra": "C"
            }),
        }),
        open_after_export: Some(false),
        target_file_name: Some(unique_name.clone()),
    };

    // Em NodeOnly, deve ser bloqueado por escopo
    let node_err = generate_document_in_directory_with_scope(
        payload.clone(),
        temp_dir.path(),
        DocumentScope::NodeOnly,
    );
    assert!(node_err.is_err());

    // Em CockpitOnly, deve gerar e gravar no diretório temporário com SHA-256 íntegro
    let result = generate_document_in_directory_with_scope(
        payload,
        temp_dir.path(),
        DocumentScope::CockpitOnly,
    )
    .expect("CessaoPosse deve ser gerada com sucesso no escopo CockpitOnly");

    assert!(result.success);
    assert_eq!(result.metadata.document_kind, DocumentKind::CessaoPosse);
    let path = Path::new(&result.file_path);
    assert!(path.starts_with(temp_dir.path()));
    let read_bytes = fs::read(path).expect("PDF de CessaoPosse deve ser legível");
    let disk_checksum = hex::encode(Sha256::digest(&read_bytes));
    assert_eq!(disk_checksum, result.metadata.sha256_checksum);
}
