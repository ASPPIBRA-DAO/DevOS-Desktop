#[test]
fn test_capabilities_zero_privilege_maintained() {
    let capability_path = Path::new("capabilities/default.json");
    assert!(
        capability_path.exists(),
        "capabilities/default.json deve existir"
    );

    let content =
        fs::read_to_string(capability_path).expect("falha ao ler capabilities/default.json");
    let parsed: serde_json::Value =
        serde_json::from_str(&content).expect("JSON invalido em default.json");

    let permissions = parsed
        .get("permissions")
        .and_then(|p| p.as_array())
        .expect("campo 'permissions' deve ser um array");

    assert!(
        permissions.is_empty(),
        "Manifesto padrao deve manter Zero Privilegio (permissions vazio), mas continha: {:?}",
        permissions
    );
}

#[test]
fn test_command_acl_manifest_autogenerated() {
    let autogen_path = Path::new("permissions/autogenerated/get_device_status.toml");
    assert!(
        autogen_path.exists(),
        "Permissoes autogeradas para get_device_status devem existir em permissions/autogenerated/"
    );

    let content = fs::read_to_string(autogen_path).expect("falha ao ler get_device_status.toml");
    assert!(content.contains("allow-get-device-status"));
    assert!(content.contains("deny-get-device-status"));

    let acl_manifest_path = Path::new("gen/schemas/acl-manifests.json");
    assert!(
        acl_manifest_path.exists(),
        "gen/schemas/acl-manifests.json deve existir para validar a ACL gerada"
    );
    let manifest_content =
        fs::read_to_string(acl_manifest_path).expect("falha ao ler gen/schemas/acl-manifests.json");
    let manifest_json: serde_json::Value = serde_json::from_str(&manifest_content)
        .expect("JSON invalido em gen/schemas/acl-manifests.json");

    let app_acl = manifest_json
        .get("__app-acl__")
        .expect("__app-acl__ deve existir em acl-manifests.json");
    assert!(
        app_acl
            .get("default_permission")
            .expect("campo default_permission deve existir")
            .is_null(),
        "default_permission deve ser nulo para que o comando nao seja implicitamente concedido"
    );

    let permissions = app_acl
        .get("permissions")
        .expect("campo permissions deve existir");
    assert!(
        permissions.get("allow-get-device-status").is_some(),
        "allow-get-device-status deve estar registrado na ACL do aplicativo"
    );
}

#[test]
fn test_persistence_initialization_and_single_migration_lifecycle() {
    let temp_dir = std::env::temp_dir().join(format!(
        "devos_test_centralized_db_{}",
        rand::random::<u32>()
    ));

    // 1. Inicializa cofre
    let vault_db = LocalDatabase::new(temp_dir.join("devos_vault"));
    MigrationManager::run_migrations(&vault_db)
        .expect("Migração do cofre deve rodar na inicialização");
    MigrationManager::run_migrations(&vault_db).expect("Migração repetida deve ser idempotente");

    // 2. Inicializa banco cadastral
    let re_db = RealEstateDatabase::new(temp_dir.join("real_estate"));
    RealEstateMigrationManager::run_migrations(&re_db)
        .expect("Migração cadastral deve rodar na inicialização");
    RealEstateMigrationManager::run_migrations(&re_db)
        .expect("Migração repetida do cadastro deve ser idempotente");

    // 3. Valida chaves estrangeiras ativas e WAL em ambas as conexões
    let conn_vault = vault_db
        .get_connection()
        .expect("Conexão com cofre deve abrir");
    let fk_vault: i32 = conn_vault
        .query_row("PRAGMA foreign_keys;", [], |r| r.get(0))
        .unwrap();
    assert_eq!(fk_vault, 1, "Foreign keys devem estar ativas no cofre");

    let conn_re = re_db
        .get_connection()
        .expect("Conexão com cadastro deve abrir");
    let fk_re: i32 = conn_re
        .query_row("PRAGMA foreign_keys;", [], |r| r.get(0))
        .unwrap();
    assert_eq!(
        fk_re, 1,
        "Foreign keys devem estar ativas no cadastro imobiliário"
    );

    let _ = fs::remove_dir_all(temp_dir);
}

#[test]
fn test_audit_events_immutability_trigger() {
    let temp_dir = std::env::temp_dir().join(format!(
        "devos_test_audit_trigger_{}",
        rand::random::<u32>()
    ));
    let re_db = RealEstateDatabase::new(temp_dir.clone());
    RealEstateMigrationManager::run_migrations(&re_db).unwrap();

    let conn = re_db.get_connection().unwrap();

    // Insere evento de auditoria
    conn.execute(
        "INSERT INTO audit_events (event_type, entity_type, entity_id, details_json, performed_by)
         VALUES ('TEST_EVENT', 'TEST_ENTITY', '1', '{}', 'TEST_USER');",
        [],
    )
    .expect("Inserção de evento deve ser permitida");

    // Tenta UPDATE no evento de auditoria (deve ser rejeitado pelo trigger)
    let update_res = conn.execute(
        "UPDATE audit_events SET performed_by = 'HACKER' WHERE id = 1;",
        [],
    );
    assert!(
        update_res.is_err(),
        "UPDATE em audit_events deve ser barrado por trigger de imutabilidade"
    );

    // Tenta DELETE no evento de auditoria (deve ser rejeitado pelo trigger)
    let delete_res = conn.execute("DELETE FROM audit_events WHERE id = 1;", []);
    assert!(
        delete_res.is_err(),
        "DELETE em audit_events deve ser barrado por trigger de imutabilidade"
    );

    let _ = fs::remove_dir_all(temp_dir);
}

#[test]
fn test_vault_and_real_estate_physical_segregation() {
    let temp_dir =
        std::env::temp_dir().join(format!("devos_test_segregation_{}", rand::random::<u32>()));

    let vault_dir = temp_dir.join("devos_vault");
    let re_dir = temp_dir.join("real_estate");

    let vault_db = LocalDatabase::new(vault_dir);
    let re_db = RealEstateDatabase::new(re_dir);

    MigrationManager::run_migrations(&vault_db).unwrap();
    RealEstateMigrationManager::run_migrations(&re_db).unwrap();

    // Verifica que são dois arquivos fisicamente separados no disco
    assert_ne!(vault_db.db_path(), re_db.db_path());
    assert!(vault_db.db_path().ends_with("devos_vault.sqlite"));
    assert!(re_db.db_path().ends_with("real_estate.sqlite"));
    assert!(vault_db.db_path().exists());
    assert!(re_db.db_path().exists());

    // Verifica que as tabelas de um não existem no outro
    let conn_vault = vault_db.get_connection().unwrap();
    let re_table_in_vault: Result<i32, _> = conn_vault.query_row(
        "SELECT 1 FROM sqlite_master WHERE type='table' AND name='properties'",
        [],
        |r| r.get(0),
    );
    assert!(
        re_table_in_vault.is_err(),
        "Tabela properties não deve existir em devos_vault.sqlite"
    );

    let conn_re = re_db.get_connection().unwrap();
    let vault_table_in_re: Result<i32, _> = conn_re.query_row(
        "SELECT 1 FROM sqlite_master WHERE type='table' AND name='vault_header'",
        [],
        |r| r.get(0),
    );
    assert!(
        vault_table_in_re.is_err(),
        "Tabela vault_header não deve existir em real_estate.sqlite"
    );

    let _ = fs::remove_dir_all(temp_dir);
}

