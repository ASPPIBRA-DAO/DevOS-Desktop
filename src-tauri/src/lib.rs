#[cfg_attr(mobile, tauri::mobile_entry_point)]
pub fn run() {
  tauri::Builder::default()
    .setup(|app| {
      if cfg!(debug_assertions) {
        app.handle().plugin(
          tauri_plugin_log::Builder::default()
            .level(log::LevelFilter::Info)
            .build(),
        )?;
      }
      Ok(())
    })
    .invoke_handler(tauri::generate_handler![
        commands::get_device_status,
        commands::get_vault_status,
        commands::init_master_password,
        commands::unlock_vault,
        commands::generate_seed_and_preview,
        commands::reveal_pending_mnemonic,
        commands::cancel_pending_creation,
        commands::confirm_and_save_wallets,
        commands::list_stored_wallets,
        commands::export_authorized_secret,
        commands::export_vault_backup,
        commands::restore_vault_backup,
        commands::fetch_wallet_balance,
        commands::batch_fetch_wallet_balances
    ])
    .run(tauri::generate_context!())
    .expect("error while building tauri application");
}

#[cfg(test)]
mod tests {
    use super::commands::*;
    use std::fs;
    use std::path::Path;

    #[test]
    fn test_get_device_status_returns_uninitialized() {
        let status = get_device_status();
        assert!(!status.enrolled);
        assert_eq!(status.status, "UNINITIALIZED");
    }

    #[test]
    fn test_capabilities_zero_privilege_maintained() {
        let capability_path = Path::new("capabilities/default.json");
        assert!(capability_path.exists(), "capabilities/default.json deve existir");

        let content = fs::read_to_string(capability_path).expect("falha ao ler capabilities/default.json");
        let parsed: serde_json::Value = serde_json::from_str(&content).expect("JSON invalido em default.json");

        let permissions = parsed
            .get("permissions")
            .and_then(|p| p.as_array())
            .expect("campo 'permissions' deve ser um array");

        assert!(
            permissions.is_empty(),
            "Manifesto padrao deve manter Zero Privilegio (permissions vazio), mas continha: {:?}",
            permissions
        );
    }

    #[test]
    fn test_command_acl_manifest_autogenerated() {
        let autogen_path = Path::new("permissions/autogenerated/get_device_status.toml");
        assert!(
            autogen_path.exists(),
            "Permissoes autogeradas para get_device_status devem existir em permissions/autogenerated/"
        );

        let content = fs::read_to_string(autogen_path).expect("falha ao ler get_device_status.toml");
        assert!(content.contains("allow-get-device-status"));
        assert!(content.contains("deny-get-device-status"));

        // Validar que o schema gerado coloca o comando sob controle de ACL com default_permission nulo
        let acl_manifest_path = Path::new("gen/schemas/acl-manifests.json");
        assert!(
            acl_manifest_path.exists(),
            "gen/schemas/acl-manifests.json deve existir para validar a ACL gerada"
        );
        let manifest_content = fs::read_to_string(acl_manifest_path)
            .expect("falha ao ler gen/schemas/acl-manifests.json");
        let manifest_json: serde_json::Value = serde_json::from_str(&manifest_content)
            .expect("JSON invalido em gen/schemas/acl-manifests.json");

        let app_acl = manifest_json.get("__app-acl__").expect("__app-acl__ deve existir em acl-manifests.json");
        assert!(
            app_acl.get("default_permission").expect("campo default_permission deve existir").is_null(),
            "default_permission deve ser nulo para que o comando nao seja implicitamente concedido"
        );

        let permissions = app_acl.get("permissions").expect("campo permissions deve existir");
        assert!(
            permissions.get("allow-get-device-status").is_some(),
            "allow-get-device-status deve estar registrado na ACL do aplicativo"
        );
    }
}
